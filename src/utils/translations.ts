export function t(key: string, locale: LocaleCode = 'en', fallback?: string): string {
  const dict = (TRANSLATIONS as any)[locale] || TRANSLATIONS.en;
  if (dict && typeof dict[key] === 'string' && dict[key].trim() !== '') {
    return dict[key];
  }
  if (TRANSLATIONS.en && typeof TRANSLATIONS.en[key] === 'string' && TRANSLATIONS.en[key].trim() !== '') {
    return TRANSLATIONS.en[key];
  }
  return fallback || key;
}
